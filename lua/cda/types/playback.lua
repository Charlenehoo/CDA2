-- ============================================================================
-- Playback 类型定义
-- ============================================================================
--
-- 本文件只描述"如何播放一段动画"。
-- 同步（ShadowControl / SetParent）、骨骼驱动、物理参数——都是别的关注点，
-- 不在这里。
--
-- 适配器产出：ActorPlayback[] —— 一个 actor 一个描述符。
-- 数组长度即 actor 数量：
--   * 长度 1 = 单人动画
--   * 长度 2 = 双人 killmove
--
-- 类型层面的约定：
--   * Alignment 一旦存在，Position / Angle 都必填——补全由适配器负责，
--     播放器不做任何 nil 判断。
--   * 没有 Kind 字段——actor 数量由数组长度表达。
--   * Duration 是最终时长（秒）——EndCycle 之类的表达方式由适配器换算，
--     播放器只认一个数。
-- ----------------------------------------------------------------------------

-- ============================================================================
-- AnimationModel：单个 actor 播什么
-- ============================================================================

---@class AnimationModelDescriptor
---@field Model    string    动画模型路径
---@field AnimName string    动画序列名
---@field Duration number    播放时长（秒）

-- ============================================================================
-- Alignment：单个 actor 摆在哪、朝哪
-- ============================================================================
-- Position / Angle 都由适配器补全——播放器只负责 SetPos / SetAngles。
-- ----------------------------------------------------------------------------

---@class AlignmentDescriptor
---@field Position Vector
---@field Angle    Angle

-- ============================================================================
-- ActorPlayback：单个 actor 的播放描述
-- ============================================================================

---@class ActorPlayback
---@field AnimationModel AnimationModelDescriptor
---@field Alignment      AlignmentDescriptor

-- ============================================================================
-- 适配器产出
-- ============================================================================

---@alias PlaybackDescriptorList ActorPlayback[]
